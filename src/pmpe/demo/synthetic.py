def build_workspace(root: Path) -> Path:
    """A git workspace with the planted code, conformance, and complexity defects."""
    root = Path(root)
    (root / "tests").mkdir(parents=True)
    (root / "deploy").mkdir()
    (root / "README.md").write_text(
        "# Demo Pinger (SYNTHETIC DEMO workspace)\n\n"
        "Generated by pmpe.demo.synthetic with deliberately planted defects —\n"
        "see examples/v2-demo/README.md.\n"
    )
    # bytecode caches are excluded from the candidate digest and must likewise
    # never dirty the git worktree (freeze rejects dirty trees)
    (root / ".gitignore").write_text("__pycache__/\n*.pyc\n")
    (root / "app.py").write_text(_APP_PLANTED)
    (root / "provider_factory.py").write_text(_FACTORY_PLANTED)
    (root / "tests" / "__init__.py").write_text("")
    (root / "tests" / "test_health.py").write_text(_TEST_HEALTH)
    (root / "deploy" / "run.sh").write_text(
        '#!/bin/sh\npython3 -c "import app; print(app.health())"\n'
    )
    (root / "deploy" / "ROLLBACK.md").write_text(
        "# Rollback\n\nRevert to the previous commit and rerun deploy/run.sh.\n"
    )
    git = LocalGitAdapter(root)
    git.init()
    git.commit_all("chore: synthetic demo workspace with planted defects")
    return root


