def run_demo(
    base_dir: Path,
    *,
    contract: Path = Path("examples/v2-demo/contract.json"),
    agents_dir: Path = Path(".claude/agents"),
    evals_dir: Path = Path("evals"),
) -> dict[str, Any]:
    base_dir = Path(base_dir)
    base_dir.mkdir(parents=True, exist_ok=True)
    workspace = build_workspace(base_dir / "workspace")
    git = LocalGitAdapter(workspace)

    run = EngineeringRun.start(contract, base_dir / "run", agents_dir=agents_dir, fixture_mode=True)
    run.record_assessment(
        {"label": "synthetic-fixture", "summary": "generated demo workspace, planted defects"}
    )
    run.submit("v2-system-architect", _architecture(run.contract_digest))
    run.submit("v2-implementation-planner", _plan(run.contract_digest))
    run.submit("v2-engineer-router", _routing())
    for agent, task in (("v2-backend-engineer", "T-001"), ("v2-test-engineer", "T-002")):
        run.submit(
            agent,
            {
                "label": "synthetic-fixture",
                "task_id": task,
                "commits": [git.log()[0].sha],
                "tests_run": [_HEALTH_TEST],
                "results": "passed",
            },
        )
    run.submit(
        "v2-integration-engineer",
        {
            "label": "synthetic-fixture",
            "integrated_branches": ["main"],
            "checks_run": ["workspace unittest suite"],
            "candidate_digest": "sha256:integrator-view",
        },
    )
    candidate = run.freeze(workspace).tree_digest

    # detection with the real machinery
    scan_before = _scan_summary(workspace)
    complexity_before = _unreferenced_modules(workspace)
    evidence_before = run_tests_with_evidence(workspace)
    mapping_before = {"FR-001": [_HEALTH_TEST], "FR-002": []}
    traceability_before = _traceability(evidence_before, mapping_before)

    coverage_evidence = (
        f"executed traceability: FR-002 = {traceability_before['FR-002']} "
        "(no test is mapped to this requirement; markers would not count anyway)"
    )
    reviews = _reviews(candidate, scan_before, coverage_evidence, complexity_before)
    for reviewer, findings in reviews.items():
        run.begin_review(reviewer, workspace)
        run.submit(
            reviewer,
            {"reviewer": reviewer, "candidate_digest": candidate, "findings": findings},
        )
        run.end_review(reviewer, workspace)

    decision = OwnerDecision(status="ACCEPTED", owner=_OWNER, reason="planted defect confirmed")
    reconciliation = run.reconcile_findings(
        {"RF-001": decision, "RF-002": decision, "RF-004": decision}, owner=_OWNER
    )

    # fix ONLY the accepted findings — real edits, real commit
    (workspace / "app.py").write_text(_APP_FIXED)
    (workspace / "provider_factory.py").unlink()
    (workspace / "tests" / "test_config.py").write_text(_TEST_CONFIG)
    fix_sha = git.commit_all(
        "fix: RF-001 RF-002 RF-004 — parse config as data, add executed "
        "FR-002 coverage, drop unjustified factory"
    )
    fixed_files = {
        "RF-001": ["app.py"],
        "RF-002": ["tests/test_config.py"],
        "RF-004": ["provider_factory.py"],
    }
    run.submit(
        "v2-approved-findings-fixer",
        {
            "label": "synthetic-fixture",
            "fixed": [
                {
                    "finding_id": fid,
                    "commits": [fix_sha],
                    "checks_rerun": ["workspace suite"],
                    "changed_files": files,
                }
                for fid, files in fixed_files.items()
            ],
        },
    )

    evidence_after = run_tests_with_evidence(workspace)
    executed = len(evidence_after.executions)
    passed = sum(1 for e in evidence_after.executions if e.outcome == "passed")
    retest_detail = f"{passed}/{executed} executed tests passed"
    run.record_gates(repo=workspace, passed=evidence_after.all_passed, detail=retest_detail)
    run.freeze(workspace)
    for finding_id, verifier in (
        ("RF-001", "v2-code-reviewer"),
        ("RF-002", "v2-product-conformance-reviewer"),
        ("RF-004", "v2-architecture-simplicity-reviewer"),
    ):
        run.record_fix_verification(finding_id, verifier=verifier)

    mapping_after = {"FR-001": [_HEALTH_TEST], "FR-002": [_CONFIG_TEST]}
    traceability_after = _traceability(evidence_after, mapping_after)
    scan_after = _scan_summary(workspace)
    complexity_after = _unreferenced_modules(workspace)

    run.record_draft_pr(
        "SYNTHETIC demo draft-PR record — the demo opens no real PR (PD-08: draft only)"
    )
    deployments: dict[str, str] = {}
    for environment in ("local", "staging"):
        run.deploy(environment, repo=workspace)  # re-verifies the frozen candidate tree
        deployments[environment] = "authorized"
    # readiness attestations come from executed evidence, not assertions
    health_verified = evidence_after.by_node().get(_HEALTH_TEST) is not None
    journey_verified = evidence_after.by_node().get(_CONFIG_TEST) is not None
    readiness = production_readiness(
        workspace, health_verified=health_verified, journey_verified=journey_verified
    )
    production_blocked_reason = ""
    try:
        run.deploy(
            "production",
            repo=workspace,
            health_verified=health_verified,
            journey_verified=journey_verified,
        )
    except DeploymentBlocked as exc:
        production_blocked_reason = str(exc)
    # binary release gates evaluated from the run's own evidence (PD-01)
    release_gates = {
        "GATE-001": all(v == "VERIFIED" for v in traceability_after.values()),
        "GATE-002": scan_after == "clean",
    }
    run.record_release_report("READY_FOR_PRODUCTION_APPROVAL", gate_results=release_gates)

    # audits over the evidence that now exists
    own_violations = evaluate_trajectory(run.ledger.read_all())
    planted_ledger = (
        evals_dir / "fixtures" / "trajectory" / "planted_implement_before_architecture.jsonl"
    )
    planted_events = [
        json.loads(line) for line in planted_ledger.read_text().splitlines() if line.strip()
    ]
    planted_violations = evaluate_trajectory(planted_events)
    drift = compare(
        json.loads((evals_dir / "baselines" / "synthetic-baseline.json").read_text()),
        json.loads(
            (evals_dir / "fixtures" / "drift" / "current_hard_gate_failure.json").read_text()
        ),
        yaml.safe_load((evals_dir / "thresholds.yaml").read_text()),
    )

    store = FindingsStore(run.run_dir)
    report: dict[str, Any] = {
        "synthetic": True,
        "label": LABEL,
        "run_id": run.status()["run_id"],
        "run_dir": str(run.run_dir),
        "workspace": str(workspace),
        "planted": {
            "code_defect": "app.py parse_config() executes operator input via eval()",
            "conformance": "FR-002 shipped with no executed test",
            "complexity": "provider_factory.py AbstractProviderFactory (unjustified)",
            "trajectory": str(planted_ledger),
            "drift": "evals/fixtures/drift/current_hard_gate_failure.json",
        },
        "detected": {
            "code_defect": scan_before,
            "code_defect_after_fix": scan_after,
            "complexity": complexity_before,
            "complexity_after_fix": complexity_after,
            "planted_trajectory": "; ".join(
                f"{v.check_id}: {v.description}" for v in planted_violations
            ),
        },
        "traceability_before": traceability_before,
        "traceability_after": traceability_after,
        "reconciliation": {
            "accepted": reconciliation.accepted,
            "rejected": reconciliation.rejected,
            "duplicates": reconciliation.duplicates,
            "product_decisions": reconciliation.product_decisions,
            "open_change_requests": [
                pcr.request_id
                for pcr in ChangeRequestStore(run.run_dir).list()
                if pcr.status == "OPEN"
            ],
        },
        "fixes": [
            {
                "finding_id": f.finding_id,
                "fixed_by": f.fixed_by,
                "verified_by": f.verified_by,
                "status": f.status,
            }
            for f in store.all()
            if f.status == "VERIFIED"
        ],
        "retest": retest_detail,
        "own_run_trajectory_violations": [f"{v.check_id}: {v.description}" for v in own_violations],
        "drift_status": drift.status,
        "deployments": deployments,
        "production_blocked": bool(production_blocked_reason),
        "production_blocked_reason": production_blocked_reason,
        "production_readiness": {"ready": readiness.ready, "missing": readiness.missing},
        "release_gates": release_gates,
        "draft_pr": run.status()["draft_pr"],
        "release_verdict": run.status()["release_verdict"],
    }
    atomic_write_json(base_dir / "demo-report.json", report)
    return report
