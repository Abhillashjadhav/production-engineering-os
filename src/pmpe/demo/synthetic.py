"""The synthetic demonstration: one complete engineering run over a workspace
with planted defects — every claim in the demo report backed by evidence the
real machinery produced.

Everything is labeled synthetic (PD-11: fixture agent artifacts stand in for
live Claude agents, so CI proves the admission/gate machinery deterministically)
and nothing touches a real environment (PD-09).

Planted failures and their detectors:
- code defect      eval() on operator input   -> deterministic security scanner
- conformance      FR-002 with no executed test -> executed traceability
- complexity       an unjustified factory      -> the simplicity review finding
- trajectory/drift pre-built planted fixtures  -> evaluate_trajectory / drift compare
"""

